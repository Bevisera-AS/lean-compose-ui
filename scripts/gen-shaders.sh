#!/usr/bin/env bash
# Compile the GLSL shader twins in shaders/ to SPIR-V and (re)generate
# Compose/Ui/Draw/Gpu/SpirvBlobs.lean with the blobs embedded as hex
# strings plus the verbatim GLSL sources (whose `include_str` staleness
# pins make editing shaders/* without regenerating a compile error).
#
# Normal builds never need this script or its tooling — the generated
# file is committed (Impeller-style offline precompile + embed).
#
# Usage:
#   scripts/gen-shaders.sh            regenerate SpirvBlobs.lean in place
#   scripts/gen-shaders.sh --check    regenerate to a temp dir and diff
#
# Tools (overridable): GLSLC=glslc SPIRV_VAL=spirv-val
# (also shipped in the Android NDK under shader-tools/<host>/).
set -euo pipefail
cd "$(dirname "$0")/.."

GLSLC=${GLSLC:-glslc}
SPIRV_VAL=${SPIRV_VAL:-spirv-val}
OUT=Compose/Ui/Draw/Gpu/SpirvBlobs.lean

# leanName  sourceFile  (stage comes from the extension)
STAGES=(
  "quadVert   quad.vert"
  "quadFrag   quad.frag"
  "shadowVert shadow.vert"
  "shadowFrag shadow.frag"
  "meshVert   mesh.vert"
  "meshFrag   mesh.frag"
  "texVert    tex.vert"
  "glyphFrag  glyph.frag"
  "layerFrag  layer.frag"
  "blurVert   blur.vert"
  "blurFrag   blur.frag"
)

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

check=0
if [[ "${1:-}" == "--check" ]]; then check=1; fi
gen="$tmp/SpirvBlobs.lean"

command -v "$GLSLC" >/dev/null || { echo "gen-shaders: $GLSLC not found (set GLSLC=)"; exit 1; }
command -v "$SPIRV_VAL" >/dev/null || { echo "gen-shaders: $SPIRV_VAL not found (set SPIRV_VAL=)"; exit 1; }

glslc_version=$("$GLSLC" --version | head -1)

# Escape a file's content into the body of a Lean string literal
# (backslash and double quote; literal newlines are valid in Lean strings).
# Command substitution strips the trailing newline — the callers below
# re-add it as a literal `\n` escape, so files must end with exactly one.
lean_escape() {
  # $(tail -c1) is empty iff the file ends with a newline; $(tail -c2) is
  # empty iff it ends with two (substitution strips trailing newlines).
  if [[ -n $(tail -c 1 "$1") || -z $(tail -c 2 "$1") ]]; then
    echo "gen-shaders: $1 must end with exactly one newline" >&2
    exit 1
  fi
  sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' "$1"
}

# Emit a ByteArray blob as a wrapped hex literal using Lean string gaps
# (a trailing backslash consumes the newline and the next line's indent).
hex_literal() {
  local spv=$1
  xxd -p "$spv" | tr -d '\n' | fold -w 96 | sed -e 's/$/\\/' -e 's/^/    /' \
    | sed -e '1s/^    //' -e '$s/\\$/"/'
}

{
  cat <<EOF
module

public import Compose.Ui.Draw.Gpu.Spirv
public meta import Compose.Ui.Draw.Gpu.Spirv

public section

/-!
# Embedded SPIR-V shader blobs (\`Compose/Ui/Draw/Gpu/SpirvBlobs.lean\`)

GENERATED by \`scripts/gen-shaders.sh\` — DO NOT EDIT BY HAND.

Compiler: $glslc_version
Flags: --target-env=vulkan1.0 -O (validated with spirv-val)

Each shader ships as (a) the verbatim GLSL source it was compiled from,
pinned against \`shaders/\` by an \`include_str\` \`#guard\` — editing a GLSL
file without rerunning the generator is a compile error — and (b) the
compiled SPIR-V as a hex string decoded by \`Spirv.ofHex\`. The GLSL
sources are dialect twins of the MSL strings in \`Gpu/Shaders.lean\`; both
cite the \`#guard\`-tested formula twins in \`Gpu/Sdf.lean\`.
-/

namespace Compose.Draw.Gpu

/-- Verbatim \`shaders/prelude.glsl\` (staleness pin only — the prelude is
inlined into each stage by \`#include\`). -/
def preludeGlsl : String := "$(lean_escape shaders/prelude.glsl)\n"

#guard (include_str ".." / ".." / ".." / ".." / "shaders" / "prelude.glsl") == preludeGlsl
EOF

  for entry in "${STAGES[@]}"; do
    read -r name file <<<"$entry"
    src="shaders/$file"
    spv="$tmp/$name.spv"
    "$GLSLC" --target-env=vulkan1.0 -I shaders -O -o "$spv" "$src"
    "$SPIRV_VAL" --target-env vulkan1.0 "$spv"
    cat <<EOF

/-- Verbatim \`$src\` (compiled into \`${name}Spv\`). -/
def ${name}Glsl : String := "$(lean_escape "$src")\n"

#guard (include_str ".." / ".." / ".." / ".." / "shaders" / "$file") == ${name}Glsl

/-- SPIR-V for \`$src\` (entrypoint \`main\`). -/
def ${name}Spv : ByteArray := Spirv.ofHex "$(hex_literal "$spv")

#guard Spirv.headerOk ${name}Spv
EOF
  done

  cat <<'EOF'

end Compose.Draw.Gpu

end
EOF
} > "$gen"

if [[ $check -eq 1 ]]; then
  if diff -u "$OUT" "$gen"; then
    echo "gen-shaders: $OUT is up to date"
  else
    echo "gen-shaders: $OUT is STALE — rerun scripts/gen-shaders.sh" >&2
    exit 1
  fi
else
  mv "$gen" "$OUT"
  echo "gen-shaders: wrote $OUT ($(wc -c <"$OUT" | tr -d ' ') bytes, ${#STAGES[@]} blobs)"
fi
